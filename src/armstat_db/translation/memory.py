"""Translation memory (TM): versioned JSONL files in ``data/translations``.

Layout::

    data/translations/
    ├── glossary.tsv          # fixed term equivalents hy/en/ru, used in prompts and reviews
    ├── hy-en.jsonl           # Armenian -> English, only where Armstat has no English text
    ├── hy-ru.jsonl           # Armenian -> Russian, for texts without official English
    ├── en-ru.jsonl           # English (official) -> Russian
    └── pending/              # generated by `armstat-db collect`, not committed
        └── {pair}.jsonl

Each memory line is ``{"source": ..., "target": ..., "engine": ..., "reviewed": false}``.
Sources are normalised with :func:`armstat_db.textutil.normalize`; files are kept sorted
by source so that diffs stay small and reviewable.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from ..textutil import normalize

PAIRS = ("hy-en", "hy-ru", "en-ru")


@dataclass
class Entry:
    source: str
    target: str
    engine: str | None = None
    reviewed: bool = False

    def to_json(self) -> str:
        return json.dumps({"source": self.source, "target": self.target,
                           "engine": self.engine, "reviewed": self.reviewed},
                          ensure_ascii=False)


class TranslationMemory:
    def __init__(self, directory: Path):
        self.directory = Path(directory)
        self.pairs: dict[str, dict[str, Entry]] = {p: {} for p in PAIRS}
        for pair in PAIRS:
            path = self.path(pair)
            if path.exists():
                with open(path, encoding="utf-8") as fh:
                    for line in fh:
                        if line.strip():
                            row = json.loads(line)
                            e = Entry(row["source"], row["target"], row.get("engine"),
                                      bool(row.get("reviewed")))
                            self.pairs[pair][e.source] = e

    def path(self, pair: str) -> Path:
        return self.directory / f"{pair}.jsonl"

    def get(self, pair: str, source: str | None) -> str | None:
        key = normalize(source)
        if key is None:
            return None
        e = self.pairs[pair].get(key)
        return e.target if e else None

    def add(self, pair: str, source: str, target: str, engine: str | None,
            overwrite: bool = False) -> bool:
        key, target = normalize(source), normalize(target)
        if not key or not target:
            return False
        current = self.pairs[pair].get(key)
        if current and (current.reviewed or not overwrite):
            return False
        self.pairs[pair][key] = Entry(key, target, engine)
        return True

    def save(self) -> None:
        self.directory.mkdir(parents=True, exist_ok=True)
        for pair, entries in self.pairs.items():
            if not entries:
                continue
            tmp = self.path(pair).with_suffix(".tmp")
            with open(tmp, "w", encoding="utf-8") as fh:
                for key in sorted(entries):
                    fh.write(entries[key].to_json() + "\n")
            tmp.replace(self.path(pair))

    def rows(self):
        for pair, entries in self.pairs.items():
            src, tgt = pair.split("-")
            for e in entries.values():
                yield src, tgt, e.source, e.target, e.engine, e.reviewed


def import_batch_results(paths, files, engine: str) -> dict:
    """Merge translated batch files into the memory.

    A batch file is JSONL with at least ``pair``, ``source`` and ``target`` keys
    (the format written by ``collect`` plus a ``target`` filled in by a translator).
    """
    tm = TranslationMemory(paths.translations_dir)
    added = skipped = 0
    for f in files:
        with open(f, encoding="utf-8") as fh:
            for line in fh:
                if not line.strip():
                    continue
                row = json.loads(line)
                if tm.add(row["pair"], row["source"], row.get("target") or "",
                          row.get("engine") or engine):
                    added += 1
                else:
                    skipped += 1
    tm.save()
    return {"added": added, "skipped": skipped}
